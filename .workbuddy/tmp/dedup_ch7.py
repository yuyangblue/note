def sub(path, pairs):
    s = open(path, encoding="utf-8").read()
    for a, b in pairs:
        n = s.count(a)
        print(("OK   " if n == 1 else "!!%d  " % n) + os.path.basename(path) + "  <-  " + a[:44].replace("\n", "|"))
        s = s.replace(a, b)
    open(path, "w", encoding="utf-8").write(s)


