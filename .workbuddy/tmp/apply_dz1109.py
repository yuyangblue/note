def save(p, s): open(p, 'w', encoding='utf-8', newline='').write(s)

def rep(s, a, b, tag):
    n = s.count(a)
    print(('OK  ' if n == 1 else '!! %d ' % n) + tag)
    assert n == 1, tag
    return s.replace(a, b)

