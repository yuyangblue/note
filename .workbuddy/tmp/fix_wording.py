import os, sys
sys.stdout.reconfigure(encoding='utf-8')

BASE = r'D:\29469\Documents\notes\计算方法与优化'
P73 = os.path.join(BASE, '第7章-非线性方程', '7.3-非线性方程组-向量函数压缩映射与牛顿法.md')
P72 = os.path.join(BASE, '第7章-非线性方程', '7.2-收敛性判据收敛阶与迭代加速-牛顿法与割线法.md')
IDX = os.path.join(BASE, '00-索引.md')

# ---------- 7.3 §20 ----------
s = open(P73, encoding='utf-8').read()
a = '课上最后用这个例子走完流程。10.28 的转写把常数丢了，配套手写笔记 p12 记下了原题：'
b = ('课上最后用这个例子走完流程。10.28 的转写把两条方程的常数丢了，只留下'
     '「三次曲线 + 圆」的形式、初值 $x^{(0)}=(1,1)^T$ 和三个偏导。'
     '下面这组方程按配套手写笔记 p12 补全：')
print('7.3 引导句', s.count(a)); assert s.count(a) == 1
s = s.replace(a, b)

anchor = ('把 $x_2=x_1^3$ 代进圆得 $x_1^6+x_1^2-1=0$；令 $t=x_1^2$ 即 $t^3+t-1=0$，'
          '唯一正根 $t=0.6823278\\ldots$，于是两个交点是 '
          '$(\\pm0.826031358,\\ \\pm0.563624162)$（同号）。'
          '两个方程、两组解，正好用来演示初值决定落到哪个解。')
note = r'''**注意：** 这组常数只有手写笔记一个来源，与录音转写无从交叉核对，所以**不能断言就是老师口述的原题**。定成 $c_1=0$ 靠两条自洽性检查：p12 第一行开头那处笔迹像 $5$ 或 $9$（放大后是方程组的大括号），若真取 $5$ 或 $9$，三次曲线与单位圆都不相交；而同页第一步给出 $F(x^{(0)})=(0,1)^T$，要求 $f_1(1,1)=0$。$c_2=1$ 是第二行直接写明的。若以后拿到课上原题的常数，以原题为准——换常数只需重跑一遍 §18 的四步，本节的结构与结论不变。

'''
print('7.3 插入锚点', s.count(anchor)); assert s.count(anchor) == 1
s = s.replace(anchor, note + anchor)
open(P73, 'w', encoding='utf-8', newline='').write(s)
print('7.3 §20 措辞已改')

